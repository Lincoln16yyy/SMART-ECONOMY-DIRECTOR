"""Trade Center fallback: buy the capacity the World Market uses.

In 1.15 the script cannot open a trade route (`create_trade_route` was removed
in 1.9), but trade capacity is generated by Trade Center levels and used to
trade with the World Market (`concept_trade_capacity_desc`, game 1.15).
Vanilla marks the building buildable by the government and by private
investors (`can_build_government` / `can_build_private` both read
`trade_center_construction_allowed`), and Isolationism disables World Market
trade (`common/scripted_triggers/00_building_triggers.txt`).

So when a good is short and the country has no producer of it at all -- the case
the import event of 0.7.21 announces -- the automatic executor may expand, or
found, a Trade Center instead of doing nothing. It never opens a route, never
sets tariffs or subventions and never builds in a state that refuses
`can_construct_building` or already has a negative infrastructure balance.
"""

VARIABLES = ['sed_trade_center_action_status', 'sed_trade_center_intent_level',
             'sed_trade_center_request_pending', 'sed_trade_center_intents',
             'sed_trade_center_completed', 'sed_trade_center_abandoned',
             'sed_trade_center_result', 'sed_trade_center_result_month',
             'sed_trade_center_candidate_states']

BUILDING = 'building_trade_center'


def triggers(goods):
    # Only a good the country cannot produce at all qualifies: `sed_plan_missing_<good>`
    # is set by the plan for a real shortage with no verified producer of the good in
    # any state. A producer that is merely waiting (labor, inputs, occupancy) or an
    # expensive-good opportunity keeps its own lane and is not routed to the market.
    # A good already answered by our own request is not a shortage to route around
    # either -- the founding in flight finishes first, like the import notice of 0.7.21.
    needs = '\n'.join(
        f'  AND = {{ var:sed_plan_missing_{good} = 1 '
        f'NOT = {{ any_scope_state = {{ sed_{good}_candidate_eligible = yes }} }} '
        f'NOT = {{ any_scope_state = {{ has_variable = sed_{good}_request_pending }} }} }}'
        for good in goods)
    return f'''# Country scope. A shortage of a good with no producer anywhere in the country,
# with trade open. Isolationism disables World Market trade, so extra capacity
# would be useless.
sed_trade_center_needed = {{
 NOT = {{ has_law = law_type:law_isolationism }}
 OR = {{
{needs}
 }}
}}

# State scope. Expand an existing Trade Center, or found the first one where the
# engine accepts the building. Skips a state whose request is already pending.
sed_trade_center_candidate_eligible = {{
 is_incorporated = yes
 infrastructure_delta >= 0
 can_construct_building = {BUILDING}
 NOT = {{ has_variable = sed_trade_center_request_pending }}
 owner = {{ sed_trade_center_needed = yes }}
 OR = {{
  NOT = {{ has_building = {BUILDING} }}
  b:{BUILDING} = {{
   level_after_queued_constructions <= level
   occupancy >= 0.5
   has_failed_hires = no
  }}
 }}
}}

sed_trade_center_approval_valid = {{
 sed_trade_center_candidate_eligible = yes
 owner = {{
  is_player = yes
  has_variable = sed_enabled
  NOT = {{ in_default = yes }}
  construction_queue_num_queued_private_levels = 0
  sed_execution_mode_permits_approval = yes
 }}
}}
'''


def effects():
    return f'''# State scope. Queue one public level and record the intent for the monthly
# review, mirroring the railway executor: only a queue count increase confirms it.
sed_run_trade_center_approval = {{
 owner = {{ if = {{ limit = {{ is_player = yes has_variable = sed_enabled has_variable = sed_mode_automatic }} sed_refresh_direct_budget = yes }} }}
 if = {{
  limit = {{ sed_trade_center_approval_valid = yes }}
  owner = {{
   set_variable = {{ name = sed_queue_levels_before value = construction_queue_num_queued_government_levels }}
  }}
  owner = {{ sed_record_auto_attempt = yes }}
  if = {{ limit = {{ has_building = {BUILDING} }}
   set_variable = {{ name = sed_trade_center_intent_level value = b:{BUILDING}.level }}
  }}
  else = {{ set_variable = {{ name = sed_trade_center_intent_level value = 0 }} }}
  start_building_construction = {BUILDING}
  owner = {{
   if = {{
    limit = {{ construction_queue_num_queued_government_levels > var:sed_queue_levels_before }}
    set_variable = {{ name = sed_trade_center_action_status value = 1 }}
    if = {{ limit = {{ has_variable = sed_trade_center_intents }}
     change_variable = {{ name = sed_trade_center_intents add = 1 }}
    }}
    else = {{ set_variable = {{ name = sed_trade_center_intents value = 1 }} }}
    prev = {{ set_variable = {{ name = sed_trade_center_request_pending value = yes }} }}
   }}
   else = {{
    set_variable = {{ name = sed_trade_center_action_status value = 2 }}
    prev = {{ remove_variable = sed_trade_center_intent_level }}
   }}
   remove_variable = sed_queue_levels_before
  }}
 }}
}}

# Completion is inferred from the queue leaving and the level rising.
sed_refresh_trade_center = {{
 if = {{ limit = {{ is_player = yes has_variable = sed_enabled }}
  set_variable = {{ name = sed_trade_center_candidate_states value = 0 }}
  every_scope_state = {{
   if = {{ limit = {{ sed_trade_center_candidate_eligible = yes }}
    root = {{ change_variable = {{ name = sed_trade_center_candidate_states add = 1 }} }}
   }}
   if = {{
    limit = {{ has_variable = sed_trade_center_request_pending
     OR = {{
      NOT = {{ has_building = {BUILDING} }}
      b:{BUILDING} = {{ level_after_queued_constructions <= level }}
     }}
    }}
    if = {{ limit = {{ has_variable = sed_trade_center_intent_level
     has_building = {BUILDING} b:{BUILDING}.level > var:sed_trade_center_intent_level }}
     owner = {{
      if = {{ limit = {{ has_variable = sed_trade_center_completed }}
       change_variable = {{ name = sed_trade_center_completed add = 1 }}
      }}
      else = {{ set_variable = {{ name = sed_trade_center_completed value = 1 }} }}
      set_variable = {{ name = sed_trade_center_result value = 1 }}
      set_variable = {{ name = sed_trade_center_result_month value = sed_live_month_key }}
     }}
    }}
    else_if = {{ limit = {{ has_variable = sed_trade_center_intent_level }}
     owner = {{
      if = {{ limit = {{ has_variable = sed_trade_center_abandoned }}
       change_variable = {{ name = sed_trade_center_abandoned add = 1 }}
      }}
      else = {{ set_variable = {{ name = sed_trade_center_abandoned value = 1 }} }}
      set_variable = {{ name = sed_trade_center_result value = 2 }}
      set_variable = {{ name = sed_trade_center_result_month value = sed_live_month_key }}
     }}
    }}
    remove_variable = sed_trade_center_intent_level
    remove_variable = sed_trade_center_request_pending
   }}
  }}
 }}
}}
'''
